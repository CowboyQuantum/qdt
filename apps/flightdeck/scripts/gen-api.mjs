// Generate src/schema/api.ts from qdt-server's OpenAPI export (ADR 0034): the control-path types, the
// same way src/schema/data.ts comes from the stream contract. `--check` fails on drift. Never edit by hand.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = new URL("../", import.meta.url);
const openapiPath = fileURLToPath(new URL("../../packages/qdt-server/exports/openapi.json", root));
const outPath = fileURLToPath(new URL("src/schema/api.ts", root));

const doc = JSON.parse(readFileSync(openapiPath, "utf8"));
const defs = doc.components.schemas;
// OpenAPI refs live under #/components/schemas; the generator wants #/$defs. Titles: keep model names only.
const rewrite = (node, keep, propertiesMap = false) => {
  if (Array.isArray(node)) return node.forEach((n) => rewrite(n, false));
  if (node === null || typeof node !== "object") return;
  if (propertiesMap) return Object.values(node).forEach((v) => rewrite(v, false)); // keys are field names
  if (!keep) delete node.title;
  if (typeof node.$ref === "string") {
    node.$ref = node.$ref.replace("#/components/schemas/", "#/$defs/");
    for (const k of Object.keys(node)) if (k !== "$ref") delete node[k];
  }
  for (const [k, v] of Object.entries(node)) {
    if (k === "properties") rewrite(v, false, true);
    else rewrite(v, k === "$defs" ? "defs" : keep === "defs");
  }
};
const wrapper = {
  $defs: defs,
  type: "object",
  additionalProperties: false,
  properties: Object.fromEntries(Object.keys(defs).map((k) => [k, { $ref: `#/$defs/${k}` }])),
};
rewrite(wrapper, false);
const banner =
  "// GENERATED by `pnpm gen:api` from packages/qdt-server/exports/openapi.json (ADR 0034).\n// Do not edit. Regenerate after any change to qdt-server's routes or the schema objects they carry.";
let ts = await compile(wrapper, "QdtControlApi", {
  bannerComment: banner,
  additionalProperties: false,
  unreachableDefinitions: true,
  style: { singleQuote: false, semi: true, printWidth: 100 },
});
ts = ts.replace(/\r\n/g, "\n");

if (process.argv.includes("--check")) {
  if (!existsSync(outPath) || readFileSync(outPath, "utf8") !== ts) {
    console.error("gen:api: DRIFT — run `pnpm gen:api` (src/schema/api.ts)");
    process.exit(1);
  }
  console.log("gen:api: OK");
} else {
  writeFileSync(outPath, ts);
  console.log(`wrote ${outPath}`);
}
