// Generate src/schema/data.ts from the qdt-schemas JSON Schema export (ADR 0005/0006).
// `--check` fails on drift (run in CI). Never edit src/schema/ by hand.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = new URL("../", import.meta.url);
const schemaPath = fileURLToPath(new URL("../../packages/qdt-schemas/exports/jsonschema/data.schema.json", root));
const outPath = fileURLToPath(new URL("src/schema/data.ts", root));

const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
// pydantic titles every property; the generator would turn each into a type alias. Keep only the
// titles of $defs entries (the model names) and the descriptions (they become doc comments).
const stripTitles = (node, keep, propertiesMap = false) => {
  if (Array.isArray(node)) return node.forEach((n) => stripTitles(n, false));
  if (node === null || typeof node !== "object") return;
  if (propertiesMap) return Object.values(node).forEach((v) => stripTitles(v, false)); // keys are field names
  if (!keep) delete node.title;
  // `{$ref, description}` makes the generator clone the referenced type (Dataset1, ...); keep the bare ref.
  if ("$ref" in node) for (const k of Object.keys(node)) if (k !== "$ref") delete node[k];
  for (const [k, v] of Object.entries(node)) {
    if (k === "properties") stripTitles(v, false, true);
    else stripTitles(v, k === "$defs" ? "defs" : keep === "defs");
  }
};
stripTitles(schema, false);
// Root is a $defs container; expose every definition as a named export.
const wrapper = {
  ...schema,
  type: "object",
  additionalProperties: false,
  properties: Object.fromEntries(Object.keys(schema.$defs).map((k) => [k, { $ref: `#/$defs/${k}` }])),
};
const banner = "// GENERATED by `pnpm gen:types` from packages/qdt-schemas/exports/jsonschema/data.schema.json.\n// Do not edit. Regenerate after any change to qdt_schemas/data.py (ADR 0010, 0011).";
let ts = await compile(wrapper, "QdtStreamContract", {
  bannerComment: banner,
  additionalProperties: false,
  unreachableDefinitions: true,
  style: { singleQuote: false, semi: true, printWidth: 100 },
});
ts = ts.replace(/\r\n/g, "\n");

if (process.argv.includes("--check")) {
  if (!existsSync(outPath) || readFileSync(outPath, "utf8") !== ts) {
    console.error("gen:types: DRIFT — run `pnpm gen:types` (src/schema/data.ts)");
    process.exit(1);
  }
  console.log("gen:types: OK");
} else {
  writeFileSync(outPath, ts);
  console.log(`wrote ${outPath}`);
}
